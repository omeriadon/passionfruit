// Generates src/lib/device-index.ts — a compact client-safe index of every
// device/accessory/product (id, name, category, link, price). The full
// catalogue JSON (1.2MB) must never enter the client bundle; this index is
// ~15KB. Regenerate after catalogue data changes:
//   node scripts/generate-device-index.mjs
import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("..", import.meta.url).pathname;

function load(path) {
	return JSON.parse(readFileSync(`${root}/${path}`, "utf8"));
}

const entries = [];

function pushDevices(file, category, href) {
	const data = load(file);
	for (const device of data.devices ?? []) {
		entries.push({
			id: device.id,
			name: device.name,
			category,
			href: href(device),
			priceAud: typeof device.priceAud === "number" ? device.priceAud : null,
		});
	}
}

pushDevices(
	"public/data/iphone/iphone.json",
	"iphone",
	(d) => `/docs/iphone/${d.id}`,
);
pushDevices("public/data/ipad/ipad.json", "ipad", (d) => `/docs/ipad/${d.id}`);
pushDevices("public/data/mac/mac.json", "mac", (d) => `/docs/mac/${d.id}`);
pushDevices(
	"public/data/apple-watch/apple-watch.json",
	"apple-watch",
	(d) => `/docs/apple-watch/${d.id}`,
);
pushDevices(
	"public/data/airpods/airpods.json",
	"airpods",
	(d) => `/docs/airpods/${d.id}`,
);
pushDevices(
	"public/data/homepod/homepod.json",
	"homepod",
	(d) => `/docs/homepod/${d.id}`,
);
pushDevices(
	"public/data/apple-tv/apple-tv.json",
	"apple-tv",
	(d) => `/docs/apple-tv/${d.id}`,
);
pushDevices(
	"public/data/vision/vision.json",
	"vision",
	(d) => `/docs/vision/${d.id}`,
);

for (const [file, section] of [
	["public/data/other/apple-pencil/apple-pencil.json", "apple-pencil"],
	["public/data/other/magic-keyboard/magic-keyboard.json", "magic-keyboard"],
]) {
	const data = load(file);
	for (const item of data.accessories ?? []) {
		entries.push({
			id: item.id,
			name: item.displayName,
			category: section,
			href: `/docs/ipad/accessories/${section}/${item.id}`,
			priceAud: typeof item.priceAud === "number" ? item.priceAud : null,
		});
	}
}

{
	const data = load("public/data/other/apple-display/apple-display.json");
	for (const product of data.products ?? []) {
		entries.push({
			id: product.id,
			name: product.displayName,
			category: "apple-display",
			href: `/docs/other/apple-display/${product.id}`,
			priceAud:
				typeof product.priceAud === "number" ? product.priceAud : null,
		});
	}
}

entries.sort((a, b) => a.name.localeCompare(b.name));

const output = `// GENERATED by scripts/generate-device-index.mjs — do not edit by hand.
// Regenerate after catalogue data changes: node scripts/generate-device-index.mjs
export type DeviceIndexEntry = {
	id: string;
	name: string;
	category: string;
	href: string;
	priceAud: number | null;
};

export const deviceIndex: DeviceIndexEntry[] = ${JSON.stringify(entries)};
`;
writeFileSync(`${root}/src/lib/device-index.ts`, output);
console.log(`Wrote ${entries.length} entries to src/lib/device-index.ts`);
